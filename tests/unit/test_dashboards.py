class ThresholdTest(unittest.TestCase):
    """A threshold lives in one place and can be set per instance.

    The KPIs used to colour heap at 85/95 and repositories at 80/90 written
    into the view, so changing nifi_threshold_heap moved the health and the
    alert but not the colour of the number next to them. And every instance
    shared one set of thresholds, which a fleet of very different NiFis
    cannot live with.
    """

    COLUMNS = ("heap_threshold", "heap_threshold_critical", "repo_threshold",
               "repo_threshold_critical", "backpressure_threshold", "bulletin_threshold")

    @classmethod
    def setUpClass(cls):
        cls.views = load_views()
        cls.macros = conf(os.path.join(APP, "default", "macros.conf"))
        cls.saved = conf(os.path.join(APP, "default", "savedsearches.conf"))
        cls.collections = conf(os.path.join(APP, "default", "collections.conf"))
        cls.transforms = conf(os.path.join(APP, "default", "transforms.conf"))
        with open(os.path.join(APP, "default", "props.conf"), encoding="utf-8") as handle:
            cls.props = handle.read()

    def test_no_view_colours_a_value_by_a_number_written_in_it(self):
        """Only counts (zero or more) may be coloured by a range in the view;
        a percentage threshold comes from the search, per instance."""
        for name, (_, d) in self.views.items():
            for viz_id, spec in d["visualizations"].items():
                for entry in (spec.get("context") or {}).get("majorColorEditorConfig", []):
                    with self.subTest(view=name, viz=viz_id):
                        self.assertIn(entry.get("from", 0), (0, 1))

    def test_the_inventory_declares_every_threshold_column(self):
        fields_list = self.transforms["instance"]["fields_list"]
        for column in self.COLUMNS:
            with self.subTest(column=column):
                self.assertEqual(self.collections["instance"].get("field." + column), "number")
                self.assertIn(column, fields_list)

    def test_every_column_overrides_its_macro_and_falls_back_on_garbage(self):
        """default_match fills every column of an unlisted host with
        "standalone": tonumber() is what makes that fall back to the macro."""
        definition = self.macros["nifi_thresholds"]["definition"]
        for column in self.COLUMNS:
            with self.subTest(column=column):
                self.assertIn("tonumber(%s)" % column, definition)

    def test_the_automatic_lookup_adds_only_the_cluster(self):
        """A bare OUTPUT would stamp the threshold columns -- "standalone" for
        an unlisted host -- into every event."""
        for line in self.props.splitlines():
            if line.startswith("LOOKUP-instance"):
                with self.subTest(line=line):
                    self.assertTrue(line.rstrip().endswith("OUTPUT cluster"), line)

    def test_health_uses_the_instance_thresholds(self):
        definition = self.macros["nifi_health"]["definition"]
        for name in ("heap_warn", "heap_crit", "repo_warn", "repo_crit",
                     "nifi_threshold_bulletins_degraded"):
            with self.subTest(name=name):
                self.assertIn(name, definition)
        self.assertIn("`nifi_thresholds`", self.macros["nifi_fleet"]["definition"])

    def test_no_alert_hardcodes_a_window_or_a_count(self):
        for name in self.saved.sections():
            search = self.saved[name].get("search")
            with self.subTest(alert=name):
                self.assertNotIn("3600000", search)
                self.assertNotRegex(search, r"n <= \d")
                self.assertNotIn("`nifi_threshold_heap`", search)
                self.assertNotIn("`nifi_threshold_repo`", search)
                self.assertNotIn("`nifi_threshold_backpressure`", search)
